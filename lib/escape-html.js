/**
 * Shared HTML escaper for admin/student UI string interpolation.
 * Escapes & < > " ' so values are safe in text and both quote styles of attributes.
 */
function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

module.exports = { escapeHtml };
